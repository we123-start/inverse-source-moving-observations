function [suPhshu,suPcshu,suPeshu]=superbasicu(x,y,superhx,superhy)
% basic function.
suPhshu=[x.*y.*(x-1).*(y-1)/4;...
                  y.*(y-1).*(1-x.^2)/2;...
                  x.*y.*(x+1).*(y-1)/4;...
                 x.*(x-1).*(1-y.^2)/2;...
                  (1-x.^2).*(1-y.^2);...
                x.*(x+1).*(1-y.^2)/2;...
                x.*y.*(x-1).*(y+1)/4;...
                 y.*(1-x.^2).*(1+y)/2; ...
                 x.*y.*(x+1).*(y+1)/4];
             
        suPcshu=[y.*(2*x-1).*(y-1)/4;...
                 x.*y.*(1-y);...
                 y.*(2*x+1).*(y-1)/4;...
                (2*x-1).*(1-y.^2)/2;...
                 2*x.*(y.^2-1);...
                (2*x+1).*(1-y.^2)/2;...
                 y.*(2*x-1).*(y+1)/4;...
                 -2*x.*y.*(1+y)/2;...
                 y.*(2*x+1).*(y+1)/4]/superhx;
             
          suPeshu=[x.*(x-1).*(2*y-1)/4;...
                   (1-x.^2).*(2*y-1)/2;...
                    x.*(x+1).*(2*y-1)/4;...
                    -x.*y.*(x-1);...
                    (1-x.^2).*(-2*y);...
                    -x.*y.*(x+1);...
                     x.*(x-1).*(2*y+1)/4;...
                     (1-x.^2).*(2*y+1)/2;...
                      x.*(x+1).*(2*y+1)/4]/superhy; 