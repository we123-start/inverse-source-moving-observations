function [wBest,bestValue,trials]=solve_map_sqp(post,w0)
% One deterministic constrained SQP run followed by the original refinement.
% Both passes use the same original MAP objective and geometric constraints.
% No multistart candidates, checkpoint, warm start, or saved solution are used.
w0=w0(:);
d=numel(w0);
lb=-24*ones(d,1);ub=24*ones(d,1);
assert(all(isfinite(w0)) && all(w0>=lb) && all(w0<=ub), ...
    'The MAP initial point must be finite and inside [-24,24].');
[c0,ceq0]=map_constraints(w0,post.kind);
assert(isempty(ceq0) && all(isfinite(c0)) && all(c0<-1e-8), ...
    'The MAP initial point is not strictly geometrically admissible.');
opts=optimoptions('fmincon','Algorithm','sqp', ...
    'Display','off','SpecifyObjectiveGradient',true, ...
    'MaxIterations',320,'MaxFunctionEvaluations',4500, ...
    'StepTolerance',2e-10,'OptimalityTolerance',5e-7, ...
    'ConstraintTolerance',2e-8);
fprintf('    Single-start SQP: shape=%s, w0=%s\n', ...
    post.kind,mat2str(w0.',8));
tStart=tic;
[w,~,exitflag,stats]=fmincon(@(z)map_objective(z,post),w0, ...
    [],[],[],[],lb,ub,@(z)map_constraints(z,post.kind),opts);
[c,ceq]=map_constraints(w,post.kind);
bestValue=map_objective(w,post);
assert(isempty(ceq) && all(isfinite(c)) && all(c<=2e-7) && ...
    isfinite(bestValue) && isfinite(li_phi_grad(w,post)), ...
    'Single-start SQP produced no finite geometrically feasible point.');
wBest=w(:);
iterations=0;
if isstruct(stats) && isfield(stats,'iterations'),iterations=stats.iterations;end
trials=struct('startId',1,'objective',bestValue,'status','completed', ...
    'exitflag',exitflag,'iterations',iterations,'w',w(:), ...
    'refinementAttempted',false,'refinementExitFlag',NaN, ...
    'refinementIterations',NaN,'refinementObjective',NaN, ...
    'refinementAccepted',false,'finalCandidateExitFlag',exitflag);

fprintf('    SQP: J=%.10g, exitflag=%d, %.1fs\n', ...
    bestValue,exitflag,toc(tStart));
if exitflag<=0
    warning('MAP:SQPExitFlag', ...
        'SQP exit flag is %d; solution may not be stationary.',exitflag);
end
% Preserve the original second-pass refinement and only accept improvement.
refine=optimoptions(opts,'MaxIterations',650, ...
    'MaxFunctionEvaluations',8000,'OptimalityTolerance',1e-8, ...
    'StepTolerance',1e-12);
tRefine=tic;
try
    trials.refinementAttempted=true;
    [wr,~,refineExitFlag,refineStats]=fmincon(@(z)map_objective(z,post),wBest, ...
        [],[],[],[],lb,ub,@(z)map_constraints(z,post.kind),refine);
    fr=map_objective(wr,post);
    trials.refinementExitFlag=refineExitFlag;
    trials.refinementObjective=fr;
    if isstruct(refineStats) && isfield(refineStats,'iterations')
        trials.refinementIterations=refineStats.iterations;
    end
    [cr,ceqr]=map_constraints(wr,post.kind);
    if isempty(ceqr) && all(isfinite(cr)) && all(cr<=2e-7) && ...
            isfinite(fr) && fr<bestValue
        wBest=wr(:);bestValue=fr;
        trials.refinementAccepted=true;
        trials.finalCandidateExitFlag=refineExitFlag;
    end
catch ME
    warning('MAP:SQPRefinement', ...
        'Refinement failed (%s); retaining the initial SQP solution.',ME.message);
end
fprintf(['    Refined MAP objective: %.10g (%.1fs), ', ...
    'refinementExitFlag=%.0f, accepted=%d\n'], ...
    bestValue,toc(tRefine),trials.refinementExitFlag, ...
    trials.refinementAccepted);
end
